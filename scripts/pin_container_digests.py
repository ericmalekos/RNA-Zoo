#!/usr/bin/env python3
"""Write conf/containers_<tag>.config, pinning every RNA-Zoo image to its registry digest.

Run after the release images are built and pushed. For each image named in
conf/modules.config (ghcr.io/ericmalekos/rnazoo-*:latest, CPU and GPU variants), this asks the
registry for the manifest digest of --tag (read-only, anonymous) and writes a config that
overrides each process's container with image@sha256:<digest>, so a run is reproducible even
after the moving tags change. A missing tag is an error; nothing is written in that case.

usage: pin_container_digests.py --tag 1.0.0 [--out conf/containers_v1.0.0.config]
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ACCEPT = ", ".join([
    "application/vnd.oci.image.index.v1+json",
    "application/vnd.docker.distribution.manifest.list.v2+json",
    "application/vnd.oci.image.manifest.v1+json",
    "application/vnd.docker.distribution.manifest.v2+json",
])


def digest(repo: str, tag: str) -> str:
    token_url = f"https://ghcr.io/token?scope=repository:{repo}:pull"
    token = json.load(urllib.request.urlopen(token_url, timeout=30))["token"]
    req = urllib.request.Request(f"https://ghcr.io/v2/{repo}/manifests/{tag}", method="HEAD",
                                 headers={"Authorization": f"Bearer {token}", "Accept": ACCEPT})
    with urllib.request.urlopen(req, timeout=30) as r:
        d = r.headers.get("Docker-Content-Digest")
    if not d:
        raise RuntimeError(f"{repo}:{tag}: registry returned no digest")
    return d


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args()
    out = a.out or ROOT / "conf" / f"containers_v{a.tag}.config"
    text = (ROOT / "conf" / "modules.config").read_text()
    # process name -> (cpu image, gpu image) or a single image
    blocks = re.findall(r"withName:\s*'([A-Z0-9_]+)'\s*\{(.*?)\n    \}", text, re.S)
    lines = ["// Generated by scripts/pin_container_digests.py; do not edit by hand.",
             f"// Every RNA-Zoo image pinned to its registry digest for release {a.tag}.",
             "process {"]
    errors = []
    for name, body in blocks:
        imgs = re.findall(r"'ghcr\.io/(ericmalekos/rnazoo-[a-z0-9-]+):latest'", body)
        if not imgs:
            continue
        pinned = []
        for repo in imgs:
            try:
                pinned.append(f"ghcr.io/{repo}@{digest(repo, a.tag)}")
            except Exception as e:  # report every failure, write nothing
                errors.append(f"{repo}:{a.tag}: {e}")
        if len(pinned) == 2:
            lines.append(f"    withName: '{name}' {{ container = params.device == 'cpu' "
                         f"? '{pinned[0]}' : '{pinned[1]}' }}")
        elif len(pinned) == 1:
            lines.append(f"    withName: '{name}' {{ container = '{pinned[0]}' }}")
    lines.append("}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
